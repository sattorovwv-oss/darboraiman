-- Only the Python server can read/write; public browser keys cannot bypass moderation.
begin;
create table if not exists public.reviews (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(trim(name)) between 2 and 60),
    rating integer not null check (rating between 1 and 5),
    comment text not null check (char_length(trim(comment)) between 10 and 2000),
    created_at bigint not null default floor(extract(epoch from now()))::bigint
);
alter table public.reviews enable row level security;
revoke all on table public.reviews from anon, authenticated;
grant select, insert on table public.reviews to service_role;
grant usage, select on sequence public.reviews_id_seq to service_role;
commit;
